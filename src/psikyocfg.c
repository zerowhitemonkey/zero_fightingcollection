void psikyocfg_apply(const char *id, int difficulty) {
    if (strcmp(id, "daraku")) return;
    if (difficulty < 1) difficulty = 1;
    if (difficulty > 8) difficulty = 8;
    psikyo_eeprom_wr(0, (uint16_t)(difficulty - 1));
    psikyo_eeprom_wr(6, 0x0a);   // FREE PLAY
    psikyo_eeprom_wr(7, 0x0a);
    for (size_t i = 0; i < sizeof daraku_patch / sizeof daraku_patch[0]; ++i)
        psikyo_patch16(daraku_patch[i].addr, daraku_patch[i].expect, daraku_patch[i].val);
}

// Stato dei giocatori: byte 0x0602E99D (P1) / 0x0602E9B1 (P2), passo 0x14.
//   0x41/0x43 = in partita (selezione, incontro), 0x05 = sconfitto (countdown del continue / "PUSH START"),
//   0x00 = fuori (attract, game over). Bit 0x40 = in partita.
int psikyocfg_player_in(const char *id, int p) {
    (void)id;
    return (emu_read8(0x0602e99du + (p ? 0x14u : 0u)) & 0x40) != 0;
}
